PREFIX = config.DEFAULT_PREFIXES[0]


def escape(text: str) -> str:
    """Escape characters MDX would treat as JSX outside code spans."""
    parts = re.split(r"(`[^`]*`)", text)
    out = []
    for part in parts:
        if part.startswith("`") and part.endswith("`"):
            out.append(part)
        else:
            out.append(
                part.replace("{", "\\{").replace("}", "\\}").replace("<", "&lt;").replace(">", "&gt;")
            )
    return "".join(out)


def code(text: str) -> str:
    text = text.replace("`", "'")
    return f"`{text}`"


def flatten(command: dict[str, Any]) -> list[dict[str, Any]]:
    found = [command]
    for sub in command.get("subcommands", []):
        found.extend(flatten(sub))
    return found


def render_command(command: dict[str, Any], level: int) -> str:
    heading = "#" * level
    lines = [f"{heading} {command['name']}", "", escape(command["description"]), ""]
    syntax = f"{PREFIX}{command['name']} {command['usage']}".strip()
    rows = [("Syntax", code(syntax))]
    if command.get("example"):
        rows.append(("Example", code(f"{PREFIX}{command['name']} {command['example']}".strip())))
    if command.get("aliases"):
        rows.append(("Aliases", ", ".join(code(a) for a in command["aliases"])))
    if command.get("permissions"):
        rows.append(("Permissions", ", ".join(code(p.replace("_", " ")) for p in command["permissions"])))
    lines.append("| | |")
    lines.append("| --- | --- |")
    lines.extend(f"| **{name}** | {value} |" for name, value in rows)
    lines.append("")
    return "\n".join(lines)


def render_module(module: str, commands: list[dict[str, Any]]) -> str:
    total = sum(len(flatten(c)) for c in commands)
    body = [
        "---",
        f'title: "{module}"',
        f'description: "{total} commands in the {module} module."',
        f'icon: "{ICONS.get(module, "terminal")}"',
        "---",
        "",
        "{/* Generated by scripts/generate_docs.py - edit the command metadata in blep/cogs instead. */}",
        "",
    ]
    for command in commands:
        body.append(render_command(command, 2))
        for sub in flatten(command)[1:]:
            body.append(render_command(sub, 3))
    return "\n".join(body).rstrip() + "\n"


def render_overview(modules: dict[str, list[dict[str, Any]]]) -> str:
    total = sum(len(flatten(c)) for cmds in modules.values() for c in cmds)
    lines = [
        "---",
        'title: "Command Reference"',
        f'description: "All {total} commands, grouped by module."',
        'icon: "terminal"',
        "---",
        "",
        "{/* Generated by scripts/generate_docs.py */}",
        "",
        "Every page lists a module's commands with their syntax, an example, aliases and the",
        "permissions they need. `(argument)` is required and `<argument>` is optional.",
        "",
        "<CardGroup cols={3}>",
    ]
    for module, commands in sorted(modules.items()):
        count = sum(len(flatten(c)) for c in commands)
        lines.append(
            f'  <Card title="{module}" icon="{ICONS.get(module, "terminal")}" href="/commands/{module}">'
            f"{count} commands</Card>"
        )
    lines.append("</CardGroup>")
    return "\n".join(lines) + "\n"


def update_navigation(modules: list[str]) -> None:
    path = DOCS / "docs.json"
    data = json.loads(path.read_text())
    for tab in data["navigation"]["tabs"]:
        if tab["tab"] == "Commands":
            tab["groups"] = [
                {"group": "Commands", "pages": ["commands/overview", *[f"commands/{m}" for m in sorted(modules)]]}
            ]
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n")


async def main() -> None:
    logging.basicConfig(level=logging.ERROR)
    async with offline_bot() as bot:
        exported = export(bot)
    modules: dict[str, list[dict[str, Any]]] = {}
    for command in exported:
        if command["module"] in {"developer"}:
            continue
        modules.setdefault(command["module"], []).append(command)

    COMMANDS_DIR.mkdir(parents=True, exist_ok=True)
    for stale in COMMANDS_DIR.glob("*.mdx"):
        stale.unlink()
    for module, commands in modules.items():
        (COMMANDS_DIR / f"{module}.mdx").write_text(render_module(module, commands))
    (COMMANDS_DIR / "overview.mdx").write_text(render_overview(modules))
    update_navigation(list(modules))

    SITE_JSON.parent.mkdir(parents=True, exist_ok=True)
    SITE_JSON.write_text(json.dumps({"prefix": PREFIX, "modules": modules}, indent=2, ensure_ascii=False) + "\n")
    total = sum(len(flatten(c)) for cmds in modules.values() for c in cmds)
    print(f"Wrote {len(modules)} module pages ({total} commands) and {SITE_JSON.relative_to(ROOT)}")


if __name__ == "__main__":
    asyncio.run(main())
